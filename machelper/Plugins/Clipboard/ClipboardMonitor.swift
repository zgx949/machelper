import AppKit

/// Polls the general pasteboard and reports newly copied plain text.
///
/// Polling `changeCount` is cheap; content is only read when the count changes.
final class ClipboardMonitor {
    /// Markers set by password managers and our own `Paster` (nspasteboard.org convention).
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard: NSPasteboard
    private let interval: TimeInterval
    private let onCopy: (String) -> Void
    private var lastChangeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general, interval: TimeInterval = 0.5, onCopy: @escaping (String) -> Void) {
        self.pasteboard = pasteboard
        self.interval = interval
        self.onCopy = onCopy
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = interval / 2 // lets the system coalesce wakeups
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string) else { return }
        onCopy(text)
    }
}
